-- ROL Inventory Intelligence Platform — Oracle DDL
-- Schema: NLECO
-- All tables use rol_ prefix
-- Matches TypeORM entities under apps/api/src/entities

-- ROL_USERS
CREATE TABLE NLECO.rol_users (
  id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username        VARCHAR2(64) NOT NULL,
  password_hash   VARCHAR2(255) NOT NULL,
  display_name    VARCHAR2(120),
  email           VARCHAR2(120),
  is_active       NUMBER(1) DEFAULT 1 NOT NULL,
  created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_rol_users_username UNIQUE (username)
);

-- ROL_ROLES
CREATE TABLE NLECO.rol_roles (
  id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code            VARCHAR2(64) NOT NULL,
  name            VARCHAR2(120) NOT NULL,
  description     VARCHAR2(255),
  created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_rol_roles_code UNIQUE (code)
);

-- ROL_PERMISSIONS
CREATE TABLE NLECO.rol_permissions (
  id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code            VARCHAR2(64) NOT NULL,
  name            VARCHAR2(120) NOT NULL,
  description     VARCHAR2(255),
  created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_rol_permissions_code UNIQUE (code)
);

-- ROL_USER_ROLES
CREATE TABLE NLECO.rol_user_roles (
  id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id         NUMBER NOT NULL,
  role_id         NUMBER NOT NULL,
  created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_rol_ur_user FOREIGN KEY (user_id) REFERENCES NLECO.rol_users(id) ON DELETE CASCADE,
  CONSTRAINT fk_rol_ur_role FOREIGN KEY (role_id) REFERENCES NLECO.rol_roles(id) ON DELETE CASCADE,
  CONSTRAINT uq_rol_user_role UNIQUE (user_id, role_id)
);

-- ROL_ROLE_PERMISSIONS
CREATE TABLE NLECO.rol_role_permissions (
  id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role_id         NUMBER NOT NULL,
  permission_id   NUMBER NOT NULL,
  created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_rol_rp_role FOREIGN KEY (role_id) REFERENCES NLECO.rol_roles(id) ON DELETE CASCADE,
  CONSTRAINT fk_rol_rp_perm FOREIGN KEY (permission_id) REFERENCES NLECO.rol_permissions(id) ON DELETE CASCADE,
  CONSTRAINT uq_rol_role_perm UNIQUE (role_id, permission_id)
);

-- ROL_AUDIT_LOGS
-- Note: Oracle reserved word RESOURCE → column resource_name
CREATE TABLE NLECO.rol_audit_logs (
  id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id         NUMBER,
  username        VARCHAR2(64),
  action_code     VARCHAR2(64) NOT NULL,
  resource_name   VARCHAR2(64),
  resource_id     VARCHAR2(64),
  details         CLOB,
  ip_address      VARCHAR2(64),
  created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX ix_rol_audit_created ON NLECO.rol_audit_logs (created_at);

-- ROL_SYSTEM_CONFIG
-- Note: avoid reserved/keyword column names key/value → config_key / config_value
CREATE TABLE NLECO.rol_system_config (
  id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  config_key      VARCHAR2(128) NOT NULL,
  config_value    CLOB,
  description     VARCHAR2(255),
  created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_rol_system_config_key UNIQUE (config_key)
);

-- ROL_SOURCE_REPORTS
CREATE TABLE NLECO.rol_source_reports (
  id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  file_name       VARCHAR2(255) NOT NULL,
  file_path       VARCHAR2(1024),
  file_hash       VARCHAR2(64) NOT NULL,
  run_date        DATE,
  period_key      VARCHAR2(7),
  row_count       NUMBER DEFAULT 0,
  status          VARCHAR2(32) DEFAULT 'pending',
  error_message   CLOB,
  source_type     VARCHAR2(32) DEFAULT 'local',
  created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_rol_source_file_hash UNIQUE (file_hash)
);

-- ROL_REPORT_PROCESSING_LOGS
CREATE TABLE NLECO.rol_report_processing_logs (
  id                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
