  avg_usage_m           NUMBER(18,4),
  proc_period           NUMBER(10,2),
  safety_margin         NUMBER(10,2),
  rol                   NUMBER(18,4),
  roq                   NUMBER(18,4),
  stock_total           NUMBER(18,4),
  po_ops                NUMBER(18,4),
  reorder_flag          VARCHAR2(3),
  avg_cost              NUMBER(18,4),
  quot_ops              NUMBER(18,4),
  transfer_to_project   NUMBER(18,4),
  final_stock           NUMBER(18,4),
  rol_touch             NUMBER(18,4),
  project_req           NUMBER(18,4),
  project_quot          NUMBER(18,4),
  project_po            NUMBER(18,4),
  actual_req            NUMBER(18,4),
  notes_raw             VARCHAR2(1000),
  is_partial            NUMBER(1) DEFAULT 0 NOT NULL,
  source_report_id      NUMBER,
  created_at            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_rol_snap_item_period UNIQUE (item_code, period_key)
);

CREATE INDEX ix_rol_snap_period ON NLECO.rol_monthly_inventory_snapshots (period_key);
CREATE INDEX ix_rol_snap_item ON NLECO.rol_monthly_inventory_snapshots (item_code);

-- ROL_STOCK_METRICS
CREATE TABLE NLECO.rol_stock_metrics (
  id                    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_code             VARCHAR2(32) NOT NULL,
  period_key            VARCHAR2(7) NOT NULL,
  stock_total           NUMBER(18,4),
  rol                   NUMBER(18,4),
  stock_delta           NUMBER(18,4),
  stock_delta_pct       NUMBER(18,4),
  gap_qty               NUMBER(18,4),
  gap_value             NUMBER(18,4),
  rol_ratio             NUMBER(18,6),
  stock_status          VARCHAR2(32) NOT NULL,
  trend_label           VARCHAR2(48),
  volatility            NUMBER(18,6),
  is_high_volatility    NUMBER(1) DEFAULT 0 NOT NULL,
  recommended_action    VARCHAR2(255),
  created_at            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at            TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_rol_metric_item_period UNIQUE (item_code, period_key)
);

CREATE INDEX ix_rol_metric_period ON NLECO.rol_stock_metrics (period_key);
CREATE INDEX ix_rol_metric_status ON NLECO.rol_stock_metrics (stock_status);

-- ROL_FORECAST_RESULTS
CREATE TABLE NLECO.rol_forecast_results (
  id                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_code         VARCHAR2(32) NOT NULL,
  period_key        VARCHAR2(7),
  method            VARCHAR2(32) NOT NULL,
  horizon_months    NUMBER DEFAULT 1,
  point_forecast    NUMBER(18,4),
  lower_band        NUMBER(18,4),
  upper_band        NUMBER(18,4),
  confidence        VARCHAR2(32),
  notes             CLOB,
  created_at        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX ix_rol_forecast_item_period ON NLECO.rol_forecast_results (item_code, period_key);

-- ROL_INVENTORY_ALERTS
CREATE TABLE NLECO.rol_inventory_alerts (
  id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  item_code       VARCHAR2(32) NOT NULL,
  period_key      VARCHAR2(7) NOT NULL,
  alert_type      VARCHAR2(64) NOT NULL,
  severity        VARCHAR2(16) DEFAULT 'medium',
  message         VARCHAR2(500) NOT NULL,
  is_active       NUMBER(1) DEFAULT 1 NOT NULL,
  created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX ix_rol_alert_period_sev ON NLECO.rol_inventory_alerts (period_key, severity);
